class ResearchTools:
    """Tools for research analysis."""

    @staticmethod
    def analyze_trend(data: list, metric_name: str = "Metric") -> Dict[str, Any]:
        """
        Analyze trend in data.

        Args:
            data: List of values
            metric_name: Name of the metric

        Returns:
            Trend analysis
        """
        if len(data) < 2:
            return {
                "success": False,
                "error": "Need at least 2 data points for trend analysis"
            }

        # Calculate trend
        first = data[0]
        last = data[-1]
        change = last - first
        percent_change = (change / first * 100) if first != 0 else 0

        trend_direction = "up" if change > 0 else "down" if change < 0 else "stable"

        return {
            "success": True,
            "metric": metric_name,
            "start_value": first,
            "end_value": last,
            "change": change,
            "percent_change": percent_change,
            "direction": trend_direction
        }

    @staticmethod
    def get_best_performing(data: dict) -> Dict[str, Any]:
        """
        Identify best performing item.

        Args:
            data: Dictionary of items and values

        Returns:
            Best performing item
        """
        if not data:
            return {
                "success": False,
                "error": "No data provided"
            }

        best_item = max(data.items(), key=lambda x: x[1])

        return {
            "success": True,
            "item": best_item[0],
            "value": best_item[1]
        }
